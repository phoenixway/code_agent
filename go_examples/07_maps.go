// Приклад 07: Асоціативні масиви (мапи) в Go
// Мапи - це структури даних, які зберігають пари "ключ-значення".
// Вони схожі на словники в інших мовах програмування.

package main

import "fmt"

func main() {
	// 1. Створення мапи з використанням make()
	// Синтаксис: make(map[тип_ключа]тип_значення)
	ages := make(map[string]int)
	ages["Анна"] = 25
	ages["Петро"] = 30
	ages["Марія"] = 28

	fmt.Println("Мапа віків:", ages)
	fmt.Println("Вік Анни:", ages["Анна"])

	// 2. Створення мапи з літералом (початковими значеннями)
	colors := map[string]string{
		"червоний": "#FF0000",
		"зелений": "#00FF00",
		"синій":  "#0000FF",
	}
	fmt.Println("\nМапа кольорів:", colors)

	// 3. Перевірка наявності ключа
	// При зверненні до мапи повертається два значення:
	// - значення для ключа (або нульове значення, якщо ключа немає)
	// - булеве значення, яке вказує, чи існує ключ
	value, exists := colors["жовтий"]
	if exists {
		fmt.Println("Значення для 'жовтий':", value)
	} else {
		fmt.Println("Ключ 'жовтий' не знайдено")
	}

	// 4. Видалення елемента з мапи
	delete(colors, "синій")
	fmt.Println("\nМапа після видалення 'синій':", colors)

	// 5. Ітерація по мапі за допомогою range
	fmt.Println("\nІтерація по мапі віків:")
	for name, age := range ages {
		fmt.Printf("%s: %d років\n", name, age)
	}

	// 6. Довжина мапи (кількість елементів)
	fmt.Println("\nКількість елементів у мапі віків:", len(ages))

	// 7. Мапи зі складнішими типами значень
	departments := map[string][]string{
		"IT":        {"Анна", "Петро", "Марія"},
		"Маркетинг": {"Олексій", "Ірина"},
		"Бухгалтерія": {"Наталія"},
	}
	fmt.Println("\nСпівробітники за відділами:")
	for dept, employees := range departments {
		fmt.Printf("%s: %v\n", dept, employees)
	}

	// 8. Вкладені мапи
	studentGrades := map[string]map[string]int{
		"Анна": {"Математика": 95, "Фізика": 88},
		"Петро": {"Математика": 78, "Фізика": 92},
	}
	fmt.Println("\nОцінки студентів:")
	for student, grades := range studentGrades {
		fmt.Printf("%s: %v\n", student, grades)
	}
}