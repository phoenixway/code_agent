// Приклад 11: Вказівники в Go
// Вказівники - це змінні, які зберігають адресу пам'яті іншої змінної
package main

import "fmt"

func main() {
	fmt.Println("=== Приклад 11: Вказівники ===")

	// 1. Оголошення змінної та отримання її адреси
	x := 42
	fmt.Printf("Змінна x = %d, адреса x = %p\n", x, &x)

	// 2. Створення вказівника
	var p *int // Оголошення вказівника на int
	p = &x     // Присвоєння адреси x вказівнику p
	fmt.Printf("Вказівник p = %p, значення за вказівником *p = %d\n", p, *p)

	// 3. Зміна значення через вказівник
	*p = 100
	fmt.Printf("Після зміни через вказівник: x = %d, *p = %d\n", x, *p)

	// 4. Нульовий вказівник
	var nilPtr *int
	if nilPtr == nil {
		fmt.Println("nilPtr є нульовим вказівником")
	}

	// 5. Вказівники на структури
	type Person struct {
		Name string
		Age  int
	}

	person := Person{"Іван", 30}
	personPtr := &person

	// Доступ до полів структури через вказівник
	fmt.Printf("Ім'я через вказівник: %s, Вік: %d\n", personPtr.Name, (*personPtr).Age)

	// 6. Вказівники у функціях (передача за посиланням)
	a, b := 10, 20
	fmt.Printf("До swap: a=%d, b=%d\n", a, b)
	swap(&a, &b)
	fmt.Printf("Після swap: a=%d, b=%d\n", a, b)

	// 7. Вказівники на масиви
	arr := [3]int{1, 2, 3}
	arrPtr := &arr
	arrPtr[0] = 100 // Зміна елемента масиву через вказівник
	fmt.Printf("Масив після зміни: %v\n", arr)
}

// Функція, яка міняє місцями значення через вказівники
func swap(x, y *int) {
	temp := *x
	*x = *y
	*y = temp
}
