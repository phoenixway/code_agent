// Приклад 01: Hello World - базова програма
// Цей файл показує найпростішу програму на Go
// Для абсолютних початківців: це перша програма, яку зазвичай пишуть при вивченні нової мови програмування

package main  // Кожна програма на Go починається з оголошення пакету
              // Пакет 'main' - це особливий пакет, який вказує, що ця програма може запускатися самостійно

import "fmt"  // Імпортуємо пакет 'fmt' (format) для роботи з вводом-виводом
               // Цей пакет містить функції для друку тексту на екран

func main() {  // Функція main() - це точка входу в програму
               // Коли програма запускається, виконується код всередині цієї функції
    
    // Виводимо текст на екран
    fmt.Println("Привіт, світ!")  // Println означає "print line" - друкує рядок і переходить на новий рядок
    
    // Додаткові приклади для кращого розуміння:
    fmt.Println("--- Додаткові приклади ---")
    
    // Друк без переходу на новий рядок
    fmt.Print("Це буде ")          // Print друкує без переходу на новий рядок
    fmt.Print("в одному рядку.\n") // \n - це символ нового рядка
    
    // Форматований вивід
    name := "Олексій"
    age := 25
    fmt.Printf("Мене звати %s і мені %d років.\n", name, age)  // %s - для рядків, %d - для чисел
    
    // Просте пояснення:
    fmt.Println("\n--- Пояснення для початківців ---")
    fmt.Println("1. Кожна програма на Go має містити package main")
    fmt.Println("2. Функція main() - це місце, де починається виконання програми")
    fmt.Println("3. fmt.Println() виводить текст на екран")
    fmt.Println("4. Коментарі починаються з // і ігноруються компілятором")
    
    // Практична порада:
    fmt.Println("\n--- Практична порада ---")
    fmt.Println("Щоб запустити цю програму, виконайте в терміналі:")
    fmt.Println("  go run 01_hello_world.go")
}