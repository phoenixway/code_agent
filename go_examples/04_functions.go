// Приклад 04: Функції в Go
// Функції - це блоки коду, які виконують певну задачу.
// Вони дозволяють організувати код, уникнути повторень та зробити програму більш читабельною.
//
// Основні поняття:
// 1. Оголошення функції - створення функції з певним ім'ям та параметрами
// 2. Виклик функції - виконання коду функції
// 3. Параметри - дані, які передаються у функцію
// 4. Повернення значення - результат роботи функції
// 5. Тип функції - визначає, які параметри приймає та що повертає функція

package main

import "fmt"

func main() {
    fmt.Println("=== ПРИКЛАД 04: ФУНКЦІЇ В GO ===")
    fmt.Println("Для абсолютних початківців: цей приклад показує основи роботи з функціями")
    fmt.Println()
    
    // 1. ПРОСТА ФУНКЦІЯ БЕЗ ПАРАМЕТРІВ ТА ПОВЕРНЕННЯ
    // Функція, яка просто виводить повідомлення
    fmt.Println("1. Проста функція без параметрів:")
    sayHello() // Виклик функції
    
    // 2. ФУНКЦІЯ З ПАРАМЕТРАМИ
    // Функція, яка приймає параметри (вхідні дані)
    fmt.Println("\n2. Функція з параметрами:")
    greetPerson("Андрій", 25) // Виклик з аргументами
    greetPerson("Марія", 30)
    
    // 3. ФУНКЦІЯ, ЯКА ПОВЕРТАЄ ЗНАЧЕННЯ
    // Функція обчислює результат і повертає його
    fmt.Println("\n3. Функція, яка повертає значення:")
    sum := addNumbers(5, 3)
    fmt.Printf("   Сума 5 + 3 = %d\n", sum)
    
    // 4. ФУНКЦІЯ З КІЛЬКОМА ПОВЕРНЕНИМИ ЗНАЧЕННЯМИ
    // В Go функція може повертати кілька значень
    fmt.Println("\n4. Функція з кількома поверненими значеннями:")
    quotient, remainder := divideNumbers(10, 3)
    fmt.Printf("   10 / 3 = %d (остача %d)\n", quotient, remainder)
    
    // 5. ФУНКЦІЯ З ІМЕНОВАНИМИ ПОВЕРНЕНИМИ ЗНАЧЕННЯМИ
    // Можна задати імена для значень, які повертаються
    fmt.Println("\n5. Функція з іменованими поверненими значеннями:")
    area, perimeter := calculateRectangle(5.0, 3.0)
    fmt.Printf("   Прямокутник 5x3: площа = %.1f, периметр = %.1f\n", area, perimeter)
    
    // 6. АНОНІМНА ФУНКЦІЯ (ЛЯМБДА)
    // Функція без імені, яку можна створити прямо в коді
    fmt.Println("\n6. Анонімна функція (лямбда):")
    multiply := func(x, y int) int {
        return x * y
    }
    result := multiply(4, 6)
    fmt.Printf("   4 * 6 = %d (обчислено анонімною функцією)\n", result)
    
    // 7. РЕКУРСИВНА ФУНКЦІЯ
    // Функція, яка викликає саму себе
    fmt.Println("\n7. Рекурсивна функція (факторіал):")
    factorialResult := factorial(5)
    fmt.Printf("   Факторіал 5 = %d\n", factorialResult)
    
    // 8. ФУНКЦІЯ З ЗМІННОЮ КІЛЬКІСТЮ АРГУМЕНТІВ (VARIADIC)
    // Функція, яка може приймати будь-яку кількість аргументів
    fmt.Println("\n8. Функція зі змінною кількістю аргументів:")
    total := sumNumbers(1, 2, 3, 4, 5)
    fmt.Printf("   Сума чисел 1,2,3,4,5 = %d\n", total)
    
    fmt.Println("\n=== ПОРАДИ ДЛЯ ПОЧАТКІВЦІВ ===")
    fmt.Println("1. Називайте функції описовими іменами (add, calculate, printResult)")
    fmt.Println("2. Функція повинна робити одну конкретну роботу")
    fmt.Println("3. Уникайте занадто довгих функцій (більше 20-30 рядків)")
    fmt.Println("4. Використовуйте коментарі для пояснення складних функцій")
    fmt.Println("5. Функції з великої літери - експортуються (видно в інших пакетах)")
    fmt.Println("6. Функції з малої літери - приватні (видно тільки в поточному пакеті)")
}

// 1. ПРОСТА ФУНКЦІЯ БЕЗ ПАРАМЕТРІВ ТА ПОВЕРНЕННЯ
func sayHello() {
    fmt.Println("   Привіт! Я функція sayHello()")
}

// 2. ФУНКЦІЯ З ПАРАМЕТРАМИ
// Параметри вказуються в дужках після імені функції
// name - параметр типу string, age - параметр типу int
func greetPerson(name string, age int) {
    fmt.Printf("   Вітаю, %s! Тобі %d років.\n", name, age)
}

// 3. ФУНКЦІЯ, ЯКА ПОВЕРТАЄ ЗНАЧЕННЯ
// Тип поверненого значення вказується після дужок з параметрами
func addNumbers(a int, b int) int {
    return a + b // return - ключове слово для повернення значення
}

// 4. ФУНКЦІЯ З КІЛЬКОМА ПОВЕРНЕНИМИ ЗНАЧЕННЯМИ
// Типи повернених значень вказуються в дужках
func divideNumbers(dividend int, divisor int) (int, int) {
    quotient := dividend / divisor
    remainder := dividend % divisor
    return quotient, remainder
}

// 5. ФУНКЦІЯ З ІМЕНОВАНИМИ ПОВЕРНЕНИМИ ЗНАЧЕННЯМИ
// Можна задати імена для значень, які повертаються
// Це робить код більш читабельним
func calculateRectangle(length, width float64) (area float64, perimeter float64) {
    // Іменовані повернені значення вже оголошені, можна просто присвоїти їм значення
    area = length * width
    perimeter = 2 * (length + width)
    return // Можна просто return, значення вже відомі
}

// 7. РЕКУРСИВНА ФУНКЦІЯ
// Функція, яка викликає саму себе
func factorial(n int) int {
    if n <= 1 {
        return 1 // Базовий випадок - зупиняє рекурсію
    }
    return n * factorial(n-1) // Рекурсивний виклик
}

// 8. ФУНКЦІЯ З ЗМІННОЮ КІЛЬКІСТЮ АРГУМЕНТІВ
// ... перед типом означає, що функція приймає будь-яку кількість аргументів цього типу
func sumNumbers(numbers ...int) int {
    total := 0
    for _, num := range numbers {
        total += num
    }
    return total
}